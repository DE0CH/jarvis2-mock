// Builds src/lib/xterm-html.gen.ts: the page the app's terminal screen runs in (a WebView), with
// xterm.js, its fit addon and its CSS inlined, so it needs no network and no login. Run by
// `npm install` (postinstall); the output is generated, not committed.
const fs = require("fs");
const path = require("path");
const nm = (p) => fs.readFileSync(require.resolve(p), "utf8");
const xterm = nm("@xterm/xterm/lib/xterm.js");
const fit = nm("@xterm/addon-fit/lib/addon-fit.js");
const css = nm("@xterm/xterm/css/xterm.css");
const bridge = fs.readFileSync(path.join(__dirname, "xterm-bridge.js"), "utf8");
const html = `<!doctype html><html><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no">
<style>${css}
html,body{margin:0;height:100%;background:#0b0d11;overflow:hidden;-webkit-user-select:none;user-select:none}
#term{position:absolute;inset:6px}
</style></head><body><div id="term"></div>
<script>${xterm}</script><script>${fit}</script><script>${bridge}</script></body></html>`;
const out = path.join(__dirname, "..", "src", "lib", "xterm-html.gen.ts");
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, "// generated by scripts/build-xterm-html.js — do not edit\nexport default " + JSON.stringify(html) + ";\n");
console.log("xterm page:", out, Math.round(html.length / 1024) + " KB");
